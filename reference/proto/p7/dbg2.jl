include(joinpath(@__DIR__, "Encode.jl"))
ms = Pop.load_population("specs")
m = only(filter(x -> x.id == "specs/5", ms))
t = @elapsed law = P7.flat_law(m); println("law ", t); flush(stdout)
t = @elapsed L = encode(law, (false, false, 0)); println("encode ", t); flush(stdout)
t = @elapsed b = Gen.body(typeof(L).parameters...); println("body ", t); flush(stdout)
println(b); flush(stdout)
t = @elapsed M = Gen.define!(:x1, L, m.metabolites, [m.fitted_params; :Keq; :E_total]); println("define ", t); flush(stdout)
s = m.samples[1]
c = NamedTuple{Tuple(first.(s.concs))}(Tuple(last.(s.concs)))
p = NamedTuple{Tuple(first.(s.params))}(Tuple(last.(s.params)))
cc = Tuple(last.(s.concs)); pp = Tuple(last.(s.params))
t = @elapsed v = Gen.evaluate(L, cc, pp); println("kernel ", t, " ", v, " ", s.v); flush(stdout)
t = @elapsed v = Base.invokelatest(Gen.rate_equation, M, c, p); println("first call ", t, " ", v, " ", s.v); flush(stdout)
